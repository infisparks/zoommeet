export interface VirtualParticipant {
  identity: string;
  name: string;
  initials: string;
  isLocal: boolean;
  isHost: boolean;
  isCoHost: boolean;
  isAudioEnabled: boolean;
  isVideoEnabled: boolean;
  isHandRaised: boolean;
  isVirtual: true;
  joinTime: number;
}

/**
 * Generate N unique simulated Indian participants for webinar social proof
 */
export function generateFUsers(count: number = 200, meetingId: string = "webinar"): VirtualParticipant[] {
  const users: VirtualParticipant[] = [];
  const totalAvailable = FIRST_NAMES.length * LAST_NAMES.length;
  const targetCount = Math.min(count, Math.max(totalAvailable, 1000));

  const used = new Set<string>();
  let seed = 0;
  for (let i = 0; i < meetingId.length; i++) {
    seed = (seed * 31 + meetingId.charCodeAt(i)) & 0xffffffff;
  }

  for (let i = 0; i < targetCount; i++) {
    let fnIdx = Math.abs(seed + i * 37) % FIRST_NAMES.length;
    let lnIdx = Math.abs(seed + i * 53) % LAST_NAMES.length;

    let fullName = `${FIRST_NAMES[fnIdx]} ${LAST_NAMES[lnIdx]}`;
    let attempts = 0;
    while (used.has(fullName) && attempts < 50) {
      fnIdx = (fnIdx + 7) % FIRST_NAMES.length;
      lnIdx = (lnIdx + 11) % LAST_NAMES.length;
      fullName = `${FIRST_NAMES[fnIdx]} ${LAST_NAMES[lnIdx]}`;
      attempts++;
    }
    used.add(fullName);

    const initials = `${FIRST_NAMES[fnIdx][0]}${LAST_NAMES[lnIdx][0]}`.toUpperCase();
    const id = `fuser_${meetingId}_${i + 1}`;

    users.push({
      identity: id,
      name: fullName,
      initials,
      isLocal: false,
      isHost: false,
      isCoHost: false,
      isAudioEnabled: false,
      isVideoEnabled: false,
      isHandRaised: false,
      isVirtual: true,
      joinTime: Date.now() - Math.floor(Math.random() * 600000),
    });
  }

  return users;
}
